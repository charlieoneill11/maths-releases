#!/usr/bin/env python3
"""Convert the exact released §8.2 multipliers into Lean data.

Pass the directory containing mixed_row_checks.py and mixed_row_certificates.json.
The Lean checker verifies the affine equations independently of this importer.
"""

import argparse
from fractions import Fraction
import hashlib
from itertools import product
import json
from pathlib import Path


DIGESTS = {
    "mixed_row_checks.py": "cc06eade53e493290bfbc01ef28bffac4a8293e2f372c94abc47fd6b51f45b16",
    "mixed_row_certificates.json": "d366474e8177fbc451cedb772574589ca09230599e5282b5c6145c0392844cf0",
}

BATCHES = [
    ("completionLow", "completion 1/10<=s<1/7", 6, 1),
    ("completionHigh", "completion 1/7<=s<1/4", 6, 1),
    ("representedLow", "level 1/10<=s<1/7", 6, 8),
    ("representedMiddle", "level 1/7<=s<1/4", 6, 8),
    ("representedHigh", "level 1/4<=s<1/3", 7, 8),
]

HEADER = """/-! Published §8.2 multiplier data generated by scripts/import_exponent_certificates.py. -/

namespace ZetaSixth.Exponents.CertificateData

"""


def read_verified_release(directory):
    inputs = {}
    for filename, expected in DIGESTS.items():
        payload = (directory / filename).read_bytes()
        actual = hashlib.sha256(payload).hexdigest()
        if actual != expected:
            raise SystemExit(f"{filename} has SHA-256 {actual}, expected {expected}")
        inputs[filename] = payload
    return json.loads(inputs["mixed_row_certificates.json"])


def encode_certificate(certificate):
    target = certificate["target"]
    if target not in {"-gap", "-1"}:
        raise ValueError(f"unknown Farkas target {target!r}")
    weights = [(index, Fraction(value)) for index, value in certificate["multipliers"]]
    if any(not isinstance(index, int) or index < 0 or value < 0 for index, value in weights):
        raise ValueError("a certificate contains an invalid row index or negative multiplier")
    fields = ["g" if target == "-gap" else "1"]
    fields.extend(f"{index}:{value.numerator}:{value.denominator}" for index, value in weights)
    return " ".join(fields)


def lean_batch(name, certificates, split_count, level_count):
    keys = [
        ".".join(map(str, numbers))
        for numbers in product(range(split_count), range(2), range(7), range(level_count))
    ]
    if set(certificates) != set(keys):
        raise ValueError(f"{name} has missing or extra branch labels")
    contents = "\n".join(encode_certificate(certificates[key]) for key in keys)
    return f"def {name} : String :=\n  {json.dumps(contents)}\n\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release_code", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "ZetaSixth/ExponentProofs/CertificateData.lean",
    )
    args = parser.parse_args()
    data = read_verified_release(args.release_code)
    contents = HEADER + "".join(
        lean_batch(name, data[key], split_count, level_count)
        for name, key, split_count, level_count in BATCHES
    )
    args.output.write_text(contents + "end ZetaSixth.Exponents.CertificateData\n", encoding="utf-8")


if __name__ == "__main__":
    main()
