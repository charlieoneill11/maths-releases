# ---------- full matrices at a point: products, nontriviality, mod 2 ----------
class EvalPoint:
    """K = F_p[s]/(f) (a field when f is irreducible), x, y, z -> given elements."""
    def __init__(self, p, f, xs, ys, zs):
        self.p = p; self.mod = nmod_poly(f, p)
        self.base = [nmod_poly(v, p) % self.mod for v in (xs, ys, zs)]
        self.invs = [self._inv(b) for b in self.base]
        self.cache = {}
    def _inv(self, f):
        g, a, _ = f.xgcd(self.mod)
        assert g.degree() == 0
        return (a*(1/g[0])) % self.mod
    def zero(self):
        return nmod_poly([], self.p)
    def one(self):
        return nmod_poly([1], self.p)
    def pw(self, v, n):
        key = (v, n)
        if key not in self.cache:
            b = self.base[v] if n >= 0 else self.invs[v]
            self.cache[key] = b.pow_mod(abs(n), self.mod) if n else self.one()
        return self.cache[key]
    def mono(self, i, j, k):
        return (self.pw(0, i)*self.pw(1, j)*self.pw(2, k)) % self.mod
    def red(self, q):
        return q % self.mod

def matrix(word, ev, twist=False):
    """Full 4x4 matrix of right multiplication by the word's numerator."""
    rows = []
    for r0 in range(4):
        row = [ev.zero()]*4; row[r0] = ev.one()
        for atom in word_atoms(word):
            if twist:   # sign automorphism chi: a -> -a, b -> b (chi(g) = 2nd linear sign)
                atom = [(c*g[0][1], g) for c, g in atom]
            row = [ev.red(q) for q in row_times_atom(row, atom, ev)]
        rows.append(row)
    return rows

def matmul(M, N, ev):
    return [[ev.red(sum((M[i][k]*N[k][j] for k in range(4)), ev.zero())) for j in range(4)] for i in range(4)]

def denom(ev):
    """D = F1^80 F2^64 F3^112, F1 = x^-1 Phi3(x), F2 = x^-2 Phi5(x), F3 = y^-1 Phi3(y)."""
    X_, Y_ = ev.base[0], ev.base[1]
    F1 = ev.red((1 + X_ + X_*X_)*ev.invs[0])
    F2 = ev.red((1 + X_ + X_**2 + X_**3 + X_**4)*ev.pw(0, -2))
    F3 = ev.red((1 + Y_ + Y_*Y_)*ev.invs[1])
    return ev.red(F1.pow_mod(80, ev.mod)*F2.pow_mod(64, ev.mod)*F3.pow_mod(112, ev.mod))

# (a) both products at a random point of a large prime field
p = PRIMES[1]
ev = EvalPoint(p, [0, 1] if False else [-rng.randrange(2, p-1), 1], [0, 1], [rng.randrange(2, p-1)], [rng.randrange(2, p-1)])
# here K = F_p, with x a random residue (s = root of the linear modulus)
D = denom(ev)
Mu, Mv = matrix(data['u'], ev), matrix(data['v'], ev)
D2 = ev.red(D*D)
for P_ in (matmul(Mu, Mv, ev), matmul(Mv, Mu, ev)):
    assert all(P_[i][j] == (D2 if i == j else 0) for i in range(4) for j in range(4))
print('N_u N_v = N_v N_u = D^2 at a random point: ok')

def unit_row(word, ev, twist=False):
    Dinv = ev._inv(denom(ev))
    return [ev.red(q*Dinv) for q in matrix(word, ev, twist)[0]]

