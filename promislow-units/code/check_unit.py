"""Independent check of the integral Promislow unit (written from the paper's
definitions only; shares no code with the original checkers).

Group: the affine crystallographic group generated by
  a: v -> diag(1,-1,-1) v + (1,1,0),   b: v -> diag(-1,1,-1) v + (0,1,1),
which is the Promislow group P. Elements are (L, t), L a sign vector.
Z[P] is a free left module over S = Z[T], T = <x,y,z> the translations, with
basis 1, a, b, ab; right multiplication by an element is a 4x4 matrix over S.
"""
import json, random, sys
from flint import nmod_poly, nmod

def mul(g, h):
    (L1, t1), (L2, t2) = g, h
    return (tuple(p*q for p, q in zip(L1, L2)),
            tuple(l*s + u for l, s, u in zip(L1, t2, t1)))

def inv(g):
    L, t = g
    return (L, tuple(-l*s for l, s in zip(L, t)))

E = ((1, 1, 1), (0, 0, 0))
A = ((1, -1, -1), (1, 1, 0))
B = ((-1, 1, -1), (0, 1, 1))
def pw(g, n):
    r = E
    for _ in range(abs(n)):
        r = mul(r, g if n > 0 else inv(g))
    return r
X, Y, Z = pw(A, 2), pw(B, 2), pw(mul(A, B), 2)
assert X == ((1,1,1),(2,0,0)) and Y == ((1,1,1),(0,2,0)) and Z == ((1,1,1),(0,0,-2))
# defining relations of P
assert mul(mul(inv(B), pw(A, 2)), B) == pw(A, -2)
assert mul(mul(inv(A), pw(B, 2)), A) == pw(B, -2)
REPS = [E, A, B, mul(A, B)]
LIN = {r[0]: k for k, r in enumerate(REPS)}
assert len(LIN) == 4

def normal_form(g):
    """g = x^i y^j z^k r  ->  (i, j, k, index of r)."""
    k = LIN[g[0]]
    tau = mul(g, inv(REPS[k]))
    assert tau[0] == (1, 1, 1)
    t = tau[1]
    assert all(c % 2 == 0 for c in t)
    return (t[0]//2, t[1]//2, -t[2]//2, k)

def word_elt(*gs):
    r = E
    for g in gs:
        r = mul(r, g)
    return r

data = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'integral-pair.json'))

def atoms_of_letter(idx, sign):
    """Group-ring atoms E(c) of letter idx (1-based), as lists of (coef, g)."""
    m, hname, k = data['vertices'][idx - 1]
    h, t, w = (A, X, Y) if hname == 'a' else (B, Y, X)
    d = (m - 1)//2
    v0 = pw(w, k)
    phases = data['phases']
    seq = phases if sign > 0 else [(-s, e) for s, e in reversed(phases)]
    out = []
    for s, e in seq:
        atom = [(1, pw(t, i)) for i in range(d + 1)]
        atom += [(s, word_elt(pw(t, i), pw(v0, e), h)) for i in range(d)]
        out.append(atom)
    # centring: the letter's denominator Phi_m(t)^4 = t^(4d) F^4 with F = t^-d Phi_m(t)
    # central, so the letter equals (t^(-4d) * atom product) / F^4.
    out.append([(1, pw(t, -4*d))])
    return out

def word_atoms(word):
    out = []
    for l in word:
        out += atoms_of_letter(abs(l), 1 if l > 0 else -1)
    return out

# ---------- exact group-ring checks on single letters (dict arithmetic) ----------
def gr_mul(f, g):
    r = {}
    for a1, c1 in f.items():
        for a2, c2 in g.items():
            k = mul(a1, a2)
            r[k] = r.get(k, 0) + c1*c2
    return {k: c for k, c in r.items() if c}
def gr(atom):
    r = {}
    for c, g in atom:
        r[g] = r.get(g, 0) + c
    return {k: c for k, c in r.items() if c}
def cyclo(m, t):
    # Phi_3 = 1+t+t^2, Phi_5 = 1+t+t^2+t^3+t^4
    return {pw(t, i): 1 for i in range(m)}

for idx in (1, 2, 3):
    m, hname, k = data['vertices'][idx - 1]
    t = X if hname == 'a' else Y
    pos = atoms_of_letter(idx, 1)[:-1]; neg = atoms_of_letter(idx, -1)[:-1]
    # E(c)E(-c) = E(-c)E(c) = Phi_m(t) for each atom of the letter
    for at, an in zip(pos, reversed(neg)):
        assert gr_mul(gr(at), gr(an)) == cyclo(m, t) == gr_mul(gr(an), gr(at))
    # Phi_m(t) commutes with every atom of its letter
    for at in pos:
        assert gr_mul(cyclo(m, t), gr(at)) == gr_mul(gr(at), cyclo(m, t))
print('letter identities: E(c)E(-c) = E(-c)E(c) = Phi_m(t), Phi_m(t) commutes within each letter: ok')

