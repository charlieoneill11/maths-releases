# ---------- right-regular matrices over a commutative ring K ----------
def row_times_atom(row, atom, ev):
    """row (list of 4 K-elements) times the 4x4 matrix of `atom`."""
    new = [ev.zero()]*4
    for c, g in atom:
        for r in range(4):
            if row[r] == 0:
                continue
            i, j, k, r2 = normal_form(mul(REPS[r], g))
            new[r2] = new[r2] + row[r]*ev.mono(i, j, k)*c
    return new

class EvalPoly:
    """K = F_p[s]/(F(s)^e) with s standing for x or y; the other two variables
    are fixed nonzero residues."""
    def __init__(self, p, F, e, var, vals):
        self.p = p
        self.mod = nmod_poly(F, p)**e
        self.var = var
        s = nmod_poly([0, 1], p)
        self.gen = {+1: s, -1: self._inv(s)}
        self.vals = vals; self.cache = {}
    def _inv(self, f):
        # inverse of s modulo mod (mod has nonzero constant term)
        g, a, _ = f.xgcd(self.mod)
        assert g.degree() == 0
        return (a * (1/ g[0])) % self.mod
    def zero(self):
        return nmod_poly([], self.p)
    def power(self, n):
        key = n
        if key not in self.cache:
            base = self.gen[1 if n >= 0 else -1]
            self.cache[key] = base.pow_mod(abs(n), self.mod) if n else nmod_poly([1], self.p)
        return self.cache[key]
    def mono(self, i, j, k):
        p = self.p
        vx, vy, vz = self.vals
        if self.var == 'x':
            num = pow(vy, j, p)*pow(vz, k, p) % p
            return (self.power(i)*num) % self.mod
        else:
            num = pow(vx, i, p)*pow(vz, k, p) % p
            return (self.power(j)*num) % self.mod

def first_row(word, ev):
    row = [ev.zero()]*4
    row[0] = nmod_poly([1], ev.p)
    for atom in word_atoms(word):
        row = row_times_atom(row, atom, ev)
        row = [q % ev.mod for q in row]
    return row

PRIMES = [(1 << 61) - 1, 4611686018427387847]
PHI3, PHI5 = [1, 1, 1], [1, 1, 1, 1, 1]
TESTS = [('x', PHI3, 80, 'Phi_3(x)^80'), ('x', PHI5, 64, 'Phi_5(x)^64'), ('y', PHI3, 112, 'Phi_3(y)^112')]
rng = random.Random(20261127)
for w in ('u', 'v'):
    for var, F, e, name in TESTS:
        for p in PRIMES:
            vals = tuple(rng.randrange(2, p - 1) for _ in range(3))
            ev = EvalPoly(p, F, e, var, vals)
            row = first_row(data[w], ev)
            assert all(q == 0 for q in row), (w, name, p)
            # sharpness: not divisible by one more power
            ev1 = EvalPoly(p, F, e + 1, var, vals)
            row1 = first_row(data[w], ev1)
            sharp = any(q != 0 for q in row1)
        print(f'{w}: numerator divisible by {name} at two random specialisations (not by one more power: {sharp})')

