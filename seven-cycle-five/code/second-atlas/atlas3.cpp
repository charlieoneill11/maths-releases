// Enumerate all 33-word codes in Z_7^3, i.e. independent sets of size 33 in the
// strong cube of C_7.  A point (u,a,b) has index 49u+7a+b; a code is six 64-bit words.
//
// A code is a cyclic sequence of planes P_0..P_6 (2D codes, P_u = {(a,b): (u,a,b) in code})
// with P_u, P_{u+1} disjoint and their union a 2D code.  Then e_u = 10-|P_u|-|P_{u+1}| >= 0
// and sum_u e_u = 70 - 2*33 = 4.  Some e_u is 0; we enumerate the codes with e_0 = 0
// (P_0 u P_1 is one of the 980 maximum 2D codes) and obtain every code exactly once as
// the translate by j of such a code c', for 0 <= j <= t(c'), where t(c') is the number of
// trailing positive deficits e_6, e_5, ... of c'.
#include <bits/stdc++.h>
using namespace std;
typedef unsigned long long u64;
typedef array<u64,6> Code;

static inline int cd(int x,int y){int d=((x-y)%7+7)%7;return min(d,7-d);}
u64 N2[49];
vector<u64> maxima;          // the 980 maximum 2D codes

static inline u64 nbhd(u64 m){u64 r=0;while(m){int i=__builtin_ctzll(m);m&=m-1;r|=N2[i];}return r;}

struct Search{
  u64 P[7]; int p[7]; vector<Code> out;
  void indep(u64 avail,u64 cur,int sz,int want,vector<u64>&o){
    if(sz==want){o.push_back(cur);return;}
    if(sz+__builtin_popcountll(avail)<want)return;
    while(avail){int i=__builtin_ctzll(avail);avail&=avail-1;indep(avail&~N2[i],cur|(1ULL<<i),sz+1,want,o);}
  }
  // Meet in the middle: forward chains P_2,P_3,P_4 from P_1 and backward chains P_6,P_5,P_4
  // from P_0 are joined on P_4.
  void run(){
    const u64 full=(1ULL<<49)-1;
    unordered_map<u64,vector<pair<u64,u64>>> fwd;
    vector<u64> o2,o3,o4;
    indep(full&~nbhd(P[1]),0,0,p[2],o2);
    for(u64 a:o2){o3.clear();indep(full&~nbhd(a),0,0,p[3],o3);
      for(u64 b:o3){o4.clear();indep(full&~nbhd(b),0,0,p[4],o4);for(u64 c:o4)fwd[c].push_back({a,b});}}
    if(fwd.empty())return;
    vector<u64> o6,o5,q4;
    indep(full&~nbhd(P[0]),0,0,p[6],o6);
    for(u64 g:o6){o5.clear();indep(full&~nbhd(g),0,0,p[5],o5);
      for(u64 e:o5){q4.clear();indep(full&~nbhd(e),0,0,p[4],q4);
        for(u64 c:q4){auto it=fwd.find(c);if(it==fwd.end())continue;
          for(auto&ab:it->second){P[2]=ab.first;P[3]=ab.second;P[4]=c;P[5]=e;P[6]=g;
            Code cc{};
            for(int u=0;u<7;u++){u64 m=P[u];while(m){int i=__builtin_ctzll(m);m&=m-1;int idx=49*u+i;cc[idx>>6]|=1ULL<<(idx&63);}}
            out.push_back(cc);}}}}
  }
};

int main(int argc,char**argv){
  // argument: the total slab deficit D (default 4, i.e. codes of size (70-D)/2 = 33)
  const int D=argc>1?atoi(argv[1]):4; const int SIZE=(70-D)/2;
  for(int a=0;a<7;a++)for(int b=0;b<7;b++){u64 m=0;for(int c=0;c<7;c++)for(int e=0;e<7;e++)if(cd(a,c)<=1&&cd(b,e)<=1)m|=1ULL<<(7*c+e);N2[7*a+b]=m;}
  {Search s; vector<u64> o; s.indep((1ULL<<49)-1,0,0,10,o); maxima=o;}
  fprintf(stderr,"maximum 2D codes: %zu\n",maxima.size());
  // deficit sequences e_0..e_6 >= 0 with e_0 = 0 and sum D; plane sizes p_u = (10 - sum_j (-1)^j e_{u+j})/2
  vector<array<int,7>> sizes;
  for(int a=0;a<=D;a++)for(int b=0;a+b<=D;b++)for(int c=0;a+b+c<=D;c++)for(int d=0;a+b+c+d<=D;d++)for(int f=0;a+b+c+d+f<=D;f++){
    int e[7]={0,a,b,c,d,f,D-a-b-c-d-f}; array<int,7> p; bool ok=true;
    for(int u=0;u<7;u++){int alt=0;for(int j=0;j<7;j++)alt+=(j%2?-1:1)*e[(u+j)%7];if((10-alt)%2||10-alt<0){ok=false;break;}p[u]=(10-alt)/2;}
    for(int u=0;u<7&&ok;u++)if(p[u]+p[(u+1)%7]!=10-e[u])ok=false;
    if(ok)sizes.push_back(p);
  }
  fprintf(stderr,"deficit sequences: %zu\n",sizes.size());
  struct Start{u64 p0,p1;int s;};
  vector<Start> starts;
  // orbit representatives of the maximum 2D codes under the group H of order 392 generated by
  // swapping a,b and the maps a -> s a + t, b -> s' b + t' (three orbits, of sizes 392, 196, 392)
  auto tr2=[&](u64 m,int g)->u64{int sw=g&1,s1=g>>1&1,s2=g>>2&1,t=g>>3;int t1=t/7,t2=t%7;u64 r=0;
    while(m){int i=__builtin_ctzll(m);m&=m-1;int a=i/7,b=i%7;if(sw)swap(a,b);if(s1)a=(7-a)%7;if(s2)b=(7-b)%7;a=(a+t1)%7;b=(b+t2)%7;r|=1ULL<<(7*a+b);}return r;};
  vector<u64> reps; {set<u64> seen; for(u64 M:maxima){if(seen.count(M))continue;reps.push_back(M);for(int g=0;g<392;g++)seen.insert(tr2(M,g));}}
  fprintf(stderr,"orbits of maximum 2D codes: %zu\n",reps.size());
  for(int si=0;si<(int)sizes.size();si++)for(u64 M:reps){
    int idx[10];int n=0;u64 m=M;while(m){idx[n++]=__builtin_ctzll(m);m&=m-1;}
    for(int s=0;s<1024;s++){if(__builtin_popcount(s)!=sizes[si][0])continue;u64 p0=0;for(int i=0;i<10;i++)if(s>>i&1)p0|=1ULL<<idx[i];starts.push_back({p0,M&~p0,si});}
  }
  fprintf(stderr,"starts: %zu\n",starts.size());
  vector<vector<Code>> res(starts.size());
  #pragma omp parallel for schedule(dynamic,256)
  for(size_t i=0;i<starts.size();i++){
    Search s; s.P[0]=starts[i].p0; s.P[1]=starts[i].p1; for(int u=0;u<7;u++)s.p[u]=sizes[starts[i].s][u]; s.run(); res[i].swap(s.out);
  }
  // apply the group H to the last two coordinates of every code found; this gives every code
  // with e_0 = 0 (possibly repeatedly, when a representative has a nontrivial stabilizer)
  vector<Code> e0;
  for(auto&v:res)for(auto&c:v)for(int g=0;g<392;g++){
    Code r{};
    for(int u=0;u<7;u++){u64 m=0;for(int i=0;i<49;i++){int idx=49*u+i;if(c[idx>>6]>>(idx&63)&1)m|=1ULL<<i;}
      m=tr2(m,g);while(m){int i=__builtin_ctzll(m);m&=m-1;int idx=49*u+i;r[idx>>6]|=1ULL<<(idx&63);}}
    e0.push_back(r);
  }
  {vector<vector<Code>>().swap(res);}
  sort(e0.begin(),e0.end()); e0.erase(unique(e0.begin(),e0.end()),e0.end());
  fprintf(stderr,"codes with e_0 = 0: %zu\n",e0.size());
  vector<vector<Code>> res2(1); res2[0].swap(e0);
  // expand by translations u -> u+j
  vector<Code> all; size_t base=0;
  auto shiftcode=[&](const Code&c,int j){Code r{};for(int idx=0;idx<343;idx++)if(c[idx>>6]>>(idx&63)&1){int u=idx/49,ab=idx%49;int nidx=49*((u+j)%7)+ab;r[nidx>>6]|=1ULL<<(nidx&63);}return r;};
  for(auto&v:res2)for(auto&c:v){
    base++;
    int pl[7];for(int u=0;u<7;u++){pl[u]=0;}
    for(int idx=0;idx<343;idx++)if(c[idx>>6]>>(idx&63)&1)pl[idx/49]++;
    int e[7];for(int u=0;u<7;u++)e[u]=10-pl[u]-pl[(u+1)%7];
    int t=0;for(int u=6;u>=1&&e[u]>0;u--)t++;
    for(int j=0;j<=t;j++)all.push_back(shiftcode(c,j));
  }
  fprintf(stderr,"codes with e_0=0: %zu, all codes: %zu\n",base,all.size());
  sort(all.begin(),all.end());
  size_t before=all.size(); all.erase(unique(all.begin(),all.end()),all.end());
  fprintf(stderr,"distinct after sort: %zu (duplicates %zu)\n",all.size(),before-all.size());
  string fn="codes"+to_string(SIZE)+".bin";FILE*f=fopen(fn.c_str(),"wb");fwrite(all.data(),sizeof(Code),all.size(),f);fclose(f);
}
