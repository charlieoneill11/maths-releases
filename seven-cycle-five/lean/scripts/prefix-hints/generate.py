#!/usr/bin/env python3
"""Build the adjacent-band prefix bitmap from little-endian 3 × UInt64 records."""
from argparse import ArgumentParser
from pathlib import Path
import struct

PROFILES = "1111 1112 1113 1122 1123 1133 1222 1223 1233 1333".split()
WIDTH = 1 << 21
WORD = (1 << 64) - 1
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
RECORD = struct.Struct("<QQQ")


def mix(x):
    x = ((x ^ (x >> 30)) * 0xBF58476D1CE4E5B9) & WORD
    x = ((x ^ (x >> 27)) * 0x94D049BB133111EB) & WORD
    return x ^ (x >> 31)


def offsets(first, second, middle):
    initial = ((first * 0x9E3779B97F4A7C15) ^ second) & WORD
    value = mix(mix(initial) ^ middle)
    return value & (WIDTH - 1), (value >> 32) & (WIDTH - 1)


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="directory with PROFILE/hints.bin files")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] /
                        "SevenCycleRuntime/PrefixHintData.lean")
    parser.add_argument("--binary", type=Path, help="also emit a packed-byte reference for Lean verification")
    parser.add_argument("--profiles", nargs="+", choices=PROFILES, default=PROFILES)
    args = parser.parse_args()
    digits = bytearray((WIDTH + 5) // 6)
    reference = bytearray(WIDTH // 8) if args.binary else None
    for profile in args.profiles:
        data = (args.directory / profile / "hints.bin").read_bytes()
        if not data or len(data) % RECORD.size:
            raise ValueError(f"{profile}: partial or empty record file")
        for record in RECORD.iter_unpack(data):
            for pos in offsets(*record):
                digits[pos // 6] |= 1 << (pos % 6)
                if reference is not None:
                    reference[pos // 8] |= 1 << (pos % 8)
        print(profile, len(data) // RECORD.size)
    encoded = "".join(ALPHABET[x] for x in digits)
    chunks = [encoded[i:i + 8192] for i in range(0, len(encoded), 8192)]
    header = "/-! Generated by scripts/prefix-hints/generate.py from profiles " + ", ".join(args.profiles) + ". -/"
    body = ",\n".join(f'  "{chunk}"' for chunk in chunks)
    args.output.write_text(f"{header}\nnamespace SevenCycle.Adjacent.PrefixHintData\n\ndef chunks : Array String := #[\n{body}\n]\n\nend SevenCycle.Adjacent.PrefixHintData\n", encoding="ascii")
    if args.binary:
        args.binary.write_bytes(reference)
    print("set bits", sum(x.bit_count() for x in digits), "/", WIDTH)


if __name__ == "__main__":
    main()
